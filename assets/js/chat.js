function botSearch(q) {
  const list = (typeof ACADEMY !== "undefined" && ACADEMY.courses) ? ACADEMY.courses : [];
  const s = q.toLowerCase();
  return list.filter((c) =>
    (c.title + " " + (c.note || "") + " " + (c.provider || "")).toLowerCase().includes(s)
  ).slice(0, 5);
}

/* بحث ويكيبيديا (مجاني) */
async function wikiSearch(q) {
  try {
    const url = "https://en.wikipedia.org/w/api.php?action=query&format=json&origin=*&prop=extracts&exintro=1&explaintext=1&exsentences=3&generator=search&gsrlimit=1&gsrsearch=" + encodeURIComponent(q);
    const r = await fetch(url);
    if (!r.ok) return null;
    const j = await r.json();
    const pages = (j.query && j.query.pages) || {};
    const p = Object.values(pages)[0];
    return p ? { title: p.title, text: p.extract } : null;
  } catch (e) { return null; }
}

/* AI احتياطي (مجاني) */
async function aiAnswer(q) {
  try {
    const url = "https://text.pollinations.ai/" + encodeURIComponent("أجب بالعربية باختصار (3-5 أسطر) عن: " + q);
    const r = await fetch(url);
    if (!r.ok) return null;
    const t = (await r.text()).trim();
    return t || null;
  } catch (e) { return null; }
}

