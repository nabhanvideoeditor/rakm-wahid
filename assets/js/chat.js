/* بحث في الكورسات */
function botSearch(q) {
  if (typeof ALL === "undefined") return [];
  const s = q.toLowerCase();
  return ALL.filter((c) =>
    (c.title + " " + (c.note || "") + " " + (c.provider || "")).toLowerCase().includes(s)
  ).slice(0, 4);
}

/* توجيه بسيط: يقترح مسار حسب الإجابات */
function botRecommend(answers) {
  const [level, goal, time] = answers;
  if (goal === "أدخل دخل حر") return { id: "content-creator", why: "أسرع طريق للدخل الحر — محتوى وتصميم بالـ AI" };
  if (goal === "أفهم المجال فقط") return { id: "ai-consultant", why: "هتفهم المجال من غير ما تتعمق في الكود" };
  if (level === "مبتدئ تماماً" && time === "ساعة أو أقل") return { id: "data-scientist", why: "أقصر مسار (6 شهور) ومناسب للمبتدئ" };
  if (level === "متوسط/متقدم") return { id: "mlops", why: "أعلى راتب في السوق ومناسب لمستواك" };
  return { id: "ml-engineer", why: "المسار الأكثر طلباً والأساسي لكل تخصصات الـ AI" };
}

/* بناء رسالة نصية مع أسطر */
function botMessage(text, opts) {
  return { from: "bot", text: text, time: new Date().toLocaleTimeString("ar-EG", { hour: "2-digit", minute: "2-digit" }), ...(opts || {}) };
}

function userMessage(text) {
  return { from: "user", text: text, time: new Date().toLocaleTimeString("ar-EG", { hour: "2-digit", minute: "2-digit" }) };
}
